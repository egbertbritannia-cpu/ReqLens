"""CPU-only, provenance-gated SERF ablation from frozen prediction caches.

IMPLEMENTED_NOT_RUN on historical SERF model outputs. Reads pre-existing
prediction cache, dataset, frozen split manifest, and checkpoint FILE BYTES;
does not load/execute model weights or download/pretrain anything.

This is a *research integrity gate*, not independent verification that logits
were really generated by claimed checkpoint weights. Outputs are ALWAYS labeled
EXPLORATORY_UNVERIFIED_MODEL_PROVENANCE and are not paper evidence.

Example from repository root::

    python -m experiments.routing.run_cached_ablation \\
      --cache /local/test_prediction_cache.json \\
      --manifest /local/split_manifest.json \\
      --dataset data/exp/promise_exp.csv \\
      --selector-checkpoint /local/selector.ckpt \\
      --fusion-checkpoint /local/fusion.ckpt \\
      --output /local/ablation_exploratory.json

Both checkpoint files MUST exist and match the cache's own SHA-256 metadata.
Never commit private experiment outputs. Keep test-set selection frozen to
validation-derived thresholds. Repeated random draws are descriptive only.
"""
import argparse
import json
import statistics
from pathlib import Path

from experiments.routing.export_prediction_cache import _sha256
from experiments.routing.prediction_cache_contract import validate_cache
from experiments.routing.route_ablation import evaluate_cached
from experiments.routing.split_provenance import build_split_manifest


REPORT_STATUS = "EXPLORATORY_UNVERIFIED_MODEL_PROVENANCE"


def _read_json(path):
    with Path(path).open("r", encoding="utf-8") as stream:
        return json.load(stream)


def _verify_complete_lineage(cache, manifest, dataset_path):
    if not isinstance(cache, dict) or cache.get("status") != "UNVERIFIED_MODEL_PROVENANCE":
        raise ValueError("Cache must have UNVERIFIED_MODEL_PROVENANCE status")
    if not isinstance(manifest, dict) or manifest.get("status") != "SPLIT_RECONSTRUCTED_NOT_PREDICTIONS":
        raise ValueError("Expected a frozen split_provenance manifest")
    metadata = cache.get("metadata")
    if not isinstance(metadata, dict):
        raise ValueError("Cache metadata missing")
    if type(manifest.get("split_seed")) is not int:
        raise ValueError("Invalid split seed")
    # Reconstruct the notebook split afresh from ORIGINAL dataset bytes. This
    # catches edited, hand-arranged or mismatched split manifests.
    canonical = build_split_manifest(dataset_path, manifest["split_seed"])
    if manifest != canonical:
        raise ValueError("Frozen split manifest differs from canonical dataset-derived split")
    if metadata.get("dataset_sha256") != canonical["dataset_sha256"]:
        raise ValueError("Dataset SHA-256 differs from prediction cache")
    if metadata.get("split_seed") != canonical["split_seed"]:
        raise ValueError("Prediction split_seed does not match canonical split")
    if metadata.get("label_order") != canonical["label_order"]:
        raise ValueError("Prediction labels differ from notebook label order")
    split = metadata.get("split")
    if split not in ("validation", "test"):
        raise ValueError("Cache must be validation or test split")
    expected = canonical["splits"][split]
    records = cache.get("records")
    if not isinstance(records, list) or len(records) != len(expected):
        raise ValueError("Cache must cover the complete selected split")
    rows = validate_cache(cache)
    if len(rows) != len(expected):
        raise ValueError("Cache validation lost records")
    for index, (record, item) in enumerate(zip(records, expected)):
        if (record["source_row_index"] != item["source_row_index"] or
                record["true_label"] != item["label"]):
            raise ValueError(f"Sample order/label mismatch at split offset {index}")
    return rows, metadata, expected


def run_cached_ablation(cache_path, manifest_path, dataset_path,
                        selector_checkpoint_path, fusion_checkpoint_path,
                        output_path, random_draws=30):
    """Validate inputs and persist exploratory 8-mode ablation JSON exclusively.

    Repeated matched-rate random routing uses deterministic seeds [0, n-1].
    No statistical significance test, independent provenance proof or GPU.
    """
    if type(random_draws) is not int or not 1 <= random_draws <= 1000:
        raise ValueError("random_draws must be an integer from 1 through 1000")
    cache, manifest = _read_json(cache_path), _read_json(manifest_path)
    rows, m, expected = _verify_complete_lineage(cache, manifest, dataset_path)
    for name, checkpoint in (("selector", selector_checkpoint_path),
                             ("fusion", fusion_checkpoint_path)):
        if _sha256(checkpoint) != m.get(f"{name}_checkpoint_sha256"):
            raise ValueError(f"{name} checkpoint bytes do not match prediction cache")
    masks, diagnostics, scores = evaluate_cached(
        rows, m["label_order"], m["tau"], m["delta"], m["risky_labels"], seed=0
    )
    random_scores = [evaluate_cached(rows, m["label_order"], m["tau"], m["delta"],
                                     m["risky_labels"], seed=seed)[2]["matched_random"]
                     for seed in range(random_draws)]
    def _summary(field):
        values = [float(s[field]) for s in random_scores]
        return {"mean": statistics.fmean(values), "min": min(values), "max": max(values),
                "sample_std": statistics.stdev(values) if len(values) > 1 else None}
    per_sample = []
    for i, (record, item) in enumerate(zip(rows, expected)):
        per_sample.append({
            "sample_id": record["id"],
            "source_row_index": item["source_row_index"],
            "true_label": record["true_label"],
            "selector_pred": m["label_order"][max(range(len(record["selector_probs"])),
                                                   key=record["selector_probs"].__getitem__)],
            "fusion_pred": record["fusion_pred"],
            "confidence_trigger": masks["confidence_only"][i],
            "margin_trigger": masks["margin_only"][i],
            "risky_class_trigger": masks["risky_class_only"][i],
            "route_full": masks["full"][i],
        })
    report = {
        "status": REPORT_STATUS,
        "scientific_warning": "Synthetic or unverified logits cannot establish SERF improvement. "
                              "Checkpoint hashes and split integrity do not prove model-to-logit identity.",
        "source_cache_sha256": _sha256(cache_path),
        "source_manifest_sha256": _sha256(manifest_path),
        "dataset_sha256": m["dataset_sha256"],
        "split": m["split"], "variant": m["variant"],
        "split_seed": m["split_seed"], "train_seed": m["train_seed"],
        "notebook_path": m["notebook_path"],
        "notebook_commit_sha": m["notebook_commit_sha"],
        "label_order": list(m["label_order"]),
        "checkpoint_sha256": {"selector": m["selector_checkpoint_sha256"],
                              "fusion": m["fusion_checkpoint_sha256"]},
        "thresholds": {"tau": m["tau"], "delta": m["delta"],
                       "risky_labels": list(m["risky_labels"]),
                       "selection_split_claim": m["threshold_selection_split"]},
        "diagnostics": diagnostics,
        "eight_mode_results": scores,
        "matched_random_descriptive": {
            "draws": random_draws, "seed_policy": "integer seeds 0 through draws-1",
            "not_statistical_significance": True,
            "macro_f1": _summary("macro_f1"),
            "accuracy": _summary("accuracy"),
            "net_corrected_count": _summary("net_corrected_count"),
        },
        "sample_diagnostics": per_sample,
    }
    # Do not overwrite any prior research output; never write before all
    # checks succeed. Consumer must assess provenance independently.
    with Path(output_path).open("x", encoding="utf-8") as stream:
        json.dump(report, stream, ensure_ascii=False, indent=2, allow_nan=False)
        stream.write("\n")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--dataset", required=True)
    parser.add_argument("--selector-checkpoint", required=True)
    parser.add_argument("--fusion-checkpoint", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--random-draws", type=int, default=30)
    args = parser.parse_args()
    report = run_cached_ablation(args.cache, args.manifest, args.dataset,
                                 args.selector_checkpoint, args.fusion_checkpoint,
                                 args.output, args.random_draws)
    print(report["status"], report["split"], report["diagnostics"]["n"])


if __name__ == "__main__":
    main()
